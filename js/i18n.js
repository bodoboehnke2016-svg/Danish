export const isLang = (id) => LANGUAGES.some((l) => l.id === id);

export function detectLang() {
  const nav = (globalThis.navigator?.language || '').slice(0, 2).toLowerCase();
  return isLang(nav) ? nav : DEFAULT_LANG;
}

/** Übersetzt einen Schlüssel; fällt auf Deutsch und dann auf den Schlüssel zurück. */
export function t(lang, key, params = {}) {
  const s = STRINGS[lang]?.[key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

/** Liefert den Text eines {de, en}-Objekts in der gewünschten Sprache. */
export const tr = (obj, lang) => (obj && typeof obj === 'object' ? obj[lang] ?? obj[DEFAULT_LANG] : obj);

